import AppSidebar from '../layout/AppSidebar'

const NAV = [
  {
    id: 'dashboard',
    label: 'Dashboard',
    icon: DashboardIcon,
  },
  {
    id: 'users',
    label: 'Registered users',
    icon: UsersIcon,
  },
  {
    id: 'activity',
    label: 'Activity logs',
    icon: ActivityIcon,
  },
  {
    id: 'jarvis',
    label: 'Voice assistant',
    icon: JarvisIcon,
    href: '/jarvis',
  },
]

function navHref(id, href, linkNav) {
  if (href) return href
  if (linkNav) {
    if (id === 'dashboard') return '/admin'
    return `/admin?tab=${id}`
  }
  return null
}

export default function AdminSidebar({ active, onChange, linkNav = false }) {
  const items = NAV.map((item) => ({
    ...item,
    href: navHref(item.id, item.href, linkNav) || undefined,
  }))

  return <AppSidebar items={items} active={active} onChange={onChange} />
}

